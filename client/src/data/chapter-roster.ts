// Current directory titles come only from the current executive board.
// FOUNDERS retains historical titles for the public website's history section.
const normalizeName = (name: string) =>
  name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/\s+/g, " ");
const memberKey = (member: Member) =>
  member.photoSlug || normalizeName(member.name);
const allMembers = [...EXEC_BOARD, ...FOUNDING_CLASS, ...FOUNDERS];
const currentLeadership = new Map(EXEC_BOARD.map(m => [memberKey(m), m]));
const founders = new Set(FOUNDERS.map(memberKey));
const directory = new Map<string, Member>();
for (const member of allMembers) {
  const key = memberKey(member);
  if (!directory.has(key)) {
    directory.set(key, {
      ...member,
      role:
        currentLeadership.get(key)?.role ||
        (founders.has(key) ? "Founder" : undefined),
    });
  }
}
export const PUBLIC_CHAPTER_MEMBERS = [...directory.values()];

// Match every name already listed on the website, including full-name variants.
const nameToMember = new Map(
  allMembers.map(m => [normalizeName(m.name), directory.get(memberKey(m))!])
);
// Explicit name variants used in the chapter's Notion member pages.
for (const [alias, canonical] of [
  ["Stina Sfatcu", "Christina Sfatcu"],
  ["Vaibhava Rajesh", "Vaibhava Raja"],
  ["Brooke Bradley", "Brooke Namie Bradley"],
  ["Ryan Nguyen ⋆˙⟡", "Ryan Nguyen"],
  ["Sally Hu ˖ . ݁𝜗𝜚. ݁₊", "Sally Hu"],
]) {
  const member = nameToMember.get(normalizeName(canonical));
  if (member) nameToMember.set(normalizeName(alias), member);
}
export function chapterMemberForName(name: string) {
  return nameToMember.get(normalizeName(name));
}
export function chapterRoleForName(name: string) {
  return chapterMemberForName(name)?.role;
}
export function chapterClassForName(
  name: string
): "Founder" | "Founding" | "Alpha" {
  const member = chapterMemberForName(name);
  if (!member) return "Alpha";
  const key = memberKey(member);
  if (founders.has(key)) return "Founder";
  if (FOUNDING_CLASS.some(m => memberKey(m) === key)) return "Founding";
  return "Alpha";
}
